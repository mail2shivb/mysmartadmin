/// Structured data extracted from a document file (image or PDF).
///
/// All fields are nullable — extraction may succeed partially.
/// Callers must treat every field as optional and display the form
/// for user review before saving.
class ExtractionResult {
  const ExtractionResult({
    this.title,
    this.passportNumber,
    this.surname,
    this.givenNames,
    this.nationality,
    this.licenceNumber,
    this.categories,
    this.issueDate,
    this.expiryDate,
    this.isStub = false,
  });

  final String? title;
  final String? passportNumber;
  final String? surname;
  final String? givenNames;
  final String? nationality;
  final String? licenceNumber;
  final String? categories;
  final DateTime? issueDate;
  final DateTime? expiryDate;

  /// True when the result was generated by [StubExtractionService].
  /// Use this flag to surface a "demo data" notice in the UI.
  final bool isStub;
}
